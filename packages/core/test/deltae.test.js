import { test } from 'node:test';
import assert from 'node:assert/strict';
import { deltaE00 } from '../src/index.js';

// Pares de referencia de Sharma, Wu y Dalal (2005), "The CIEDE2000 color-difference formula: implementation notes..." (tabla 1).
// [L1, a1, b1, L2, a2, b2, ΔE00 esperado]
const SHARMA = [
  [50.0, 2.6772, -79.7751, 50.0, 0.0, -82.7485, 2.0425],
  [50.0, 3.1571, -77.2803, 50.0, 0.0, -82.7485, 2.8615],
  [50.0, 2.8361, -74.02, 50.0, 0.0, -82.7485, 3.4412],
  [50.0, -1.3802, -84.2814, 50.0, 0.0, -82.7485, 1.0],
  [50.0, 0.0, 0.0, 50.0, -1.0, 2.0, 2.3669],
  [50.0, 2.5, 0.0, 50.0, 0.0, -2.5, 4.3065],
  [50.0, 2.5, 0.0, 73.0, 25.0, -18.0, 27.1492],
  [50.0, 2.5, 0.0, 61.0, -5.0, 29.0, 22.8977],
  [50.0, 2.5, 0.0, 56.0, -27.0, -3.0, 31.903],
  [50.0, 2.5, 0.0, 58.0, 24.0, 15.0, 19.4535],
  [60.2574, -34.0099, 36.2677, 60.4626, -34.1751, 39.4387, 1.2644],
  [63.0109, -31.0961, -5.8663, 62.8187, -29.7946, -4.0864, 1.263],
  [61.2901, 3.7196, -5.3901, 61.4292, 2.248, -4.962, 1.8731],
  [35.0831, -44.1164, 3.7933, 35.0232, -40.0716, 1.5901, 1.8645],
  [22.7233, 20.0904, -46.694, 23.0331, 14.973, -42.5619, 2.0373],
  [36.4612, 47.858, 18.3852, 36.2715, 50.5065, 21.2231, 1.4146],
  [90.8027, -2.0831, 1.441, 91.1528, -1.6435, 0.0447, 1.4441],
  [90.9257, -0.5406, -0.9208, 88.6381, -0.8985, -0.7239, 1.5381],
  [6.7747, -0.2908, -2.4247, 5.8714, -0.0985, -2.2286, 0.6377],
  [2.0776, 0.0795, -1.135, 0.9033, -0.0636, -0.5514, 0.9082],
];

test('CIEDE2000: coincide con los valores de Sharma 2005 (4 decimales)', () => {
  for (const [L1, a1, b1, L2, a2, b2, esperado] of SHARMA) {
    const d = deltaE00({ L: L1, a: a1, b: b1 }, { L: L2, a: a2, b: b2 });
    assert.ok(Math.abs(d - esperado) < 1e-4, `(${L1},${a1},${b1}) vs (${L2},${a2},${b2}): ${d} ≠ ${esperado}`);
  }
});

test('CIEDE2000: es simétrica y vale 0 entre colores iguales', () => {
  const x = { L: 55, a: 20, b: -30 }, y = { L: 62, a: -5, b: 40 };
  assert.equal(deltaE00(x, x), 0);
  assert.ok(Math.abs(deltaE00(x, y) - deltaE00(y, x)) < 1e-9);
});
